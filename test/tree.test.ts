import { describe, expect, it } from "@effect/vitest";
import { exclusionReason } from "../src/pipeline/exclusion.ts";
import {
  classifyRole,
  hasGeneratedHeader,
  directoryOf,
  manifestPaths,
  packageDirOf,
  parseLsTree,
  sourceFiles,
} from "../src/deep-analysis/tree.ts";
import type { PackageJsonManifest } from "../src/analysis/package-json.ts";

const listing = [
  "100644 blob aaaa\tpackage.json",
  "100644 blob aaaa\tpackages/core/package.json",
  "100644 blob aaaa\tpackages/core/src/index.ts",
  "100644 blob aaaa\tpackages/core/src/deep/a b.tsx",
  "100644 blob aaaa\tpackages/core/test/index.test.ts",
  "100644 blob aaaa\tpackages/core/src/types.d.ts",
  "100755 blob aaaa\tscripts/run.mts",
  "120000 blob aaaa\tlinked.ts",
  "160000 commit aaaa\tsubmodule",
  "100644 blob aaaa\tnode_modules/x/package.json",
  "100644 blob aaaa\tnode_modules/x/index.ts",
  "100644 blob aaaa\tpackages/core/dist/index.ts",
  "100644 blob aaaa\tREADME.md",
  "100644 blob aaaa\t.repos/effect/package.json",
  "100644 blob aaaa\t.repos/effect/packages/effect/package.json",
  "100644 blob aaaa\t.repos/effect/packages/effect/src/Effect.ts",
  "100644 blob aaaa\t.github/scripts/release.ts",
]
  .map((line) => `${line}\0`)
  .join("");

describe("tree inventory", () => {
  const tree = parseLsTree(listing);

  it("parses NUL-separated ls-tree records, spaces in paths included", () => {
    expect(tree).toHaveLength(17);
    expect(tree[3]).toEqual({
      mode: "100644",
      type: "blob",
      path: "packages/core/src/deep/a b.tsx",
    });
  });

  it("lists manifests outside excluded and hidden directories (vendored copies)", () => {
    expect(manifestPaths(tree)).toEqual(["package.json", "packages/core/package.json"]);
  });

  it("inventories regular TS files outside excluded directories, with role and package", () => {
    const dirs = new Set(manifestPaths(tree).map(directoryOf));
    expect(sourceFiles(tree, dirs)).toEqual([
      {
        file: "packages/core/src/deep/a b.tsx",
        extension: "tsx",
        role: "source",
        declaration: false,
        packageDir: "packages/core",
      },
      {
        file: "packages/core/src/index.ts",
        extension: "ts",
        role: "source",
        declaration: false,
        packageDir: "packages/core",
      },
      {
        file: "packages/core/src/types.d.ts",
        extension: "ts",
        role: "source",
        declaration: true,
        packageDir: "packages/core",
      },
      {
        file: "packages/core/test/index.test.ts",
        extension: "ts",
        role: "test",
        declaration: false,
        packageDir: "packages/core",
      },
      {
        file: "scripts/run.mts",
        extension: "mts",
        role: "source",
        declaration: false,
        packageDir: "",
      },
    ]);
  });

  it("assigns files to the nearest package directory", () => {
    const dirs = new Set(["", "a", "a/b"]);
    expect(packageDirOf("a/b/c/d.ts", dirs)).toBe("a/b");
    expect(packageDirOf("a/x.ts", dirs)).toBe("a");
    expect(packageDirOf("z/x.ts", dirs)).toBe("");
  });

  it("classifies generated code by name and directory, before tests", () => {
    expect(classifyRole("src/routeTree.gen.ts")).toBe("generated");
    expect(classifyRole("src/schema.generated.tsx")).toBe("generated");
    expect(classifyRole("proto/user_pb.ts")).toBe("generated");
    expect(classifyRole("proto/user.pb.ts")).toBe("generated");
    expect(classifyRole("src/__generated__/graphql.ts")).toBe("generated");
    expect(classifyRole("packages/acp/src/_generated/schema.ts")).toBe("generated");
    expect(classifyRole("test/generated/fixtures.test.ts")).toBe("generated");
    expect(classifyRole("scripts/gen/generator.ts")).toBe("source");
    expect(classifyRole("src/generate.ts")).toBe("source");
    expect(classifyRole("src/regenerated-cache.ts")).toBe("source");
  });

  it("recognizes generator headers, not ordinary comments", () => {
    for (const header of [
      "// @generated by protoc-gen-es v2.2.0",
      "/* eslint-disable */\n// This file was automatically generated by TanStack Router.",
      "// Code generated by openapi-typescript. DO NOT EDIT.",
      "/**\n * This file is auto-generated. Do not edit manually.\n */",
      "/* !!! This is code generated by Prisma. Do not edit directly. !!! */",
      "// AUTOGENERATED FILE",
      "// DO NOT EDIT - generated from schema.json by scripts/codegen.ts",
      '#!/usr/bin/env node\n"use client";\n\n// Generated by @opencode-ai/httpapi-codegen. Do not edit.',
      "/**\n * @fileoverview API client\n * @generated\n */\nexport {};",
    ]) {
      expect([header, hasGeneratedHeader(header)]).toEqual([header, true]);
    }
    for (const text of [
      "// Do not edit this constant without updating the docs.",
      "// DO NOT MODIFY THIS FILE.\n// Adapted from https://github.com/Effect-TS/effect/blob/main/MockTerminal.ts",
      "// DO NOT EDIT",
      "// IDs are generated by the database.",
      "export const generated = true;",
      "export const nav = { label: 'API Reference (Auto-generated)' };",
      "const colors = 1;\nconst output = `\n/* Generated by script/tailwind.ts */\n/* Do not edit this file manually */`;",
      "'use client';\nimport { x } from 'y';\n/**\n * Renders a table.\n * Used in auto-generated index pages.\n */",
      "/**\n * This module formats auto-generated IDs for the UI.\n */\nexport const f = 1;",
      "// Generator for the icon sprites (run with bun).\nexport const run = () => {};",
      "/**\n * - draft-4 bounds are never\n *   generated: they are not part of Draft 7\n */",
      `${"x".repeat(2000)}\n// @generated`,
    ]) {
      expect([text.slice(0, 40), hasGeneratedHeader(text)]).toEqual([text.slice(0, 40), false]);
    }
  });

  it("classifies test code by name and directory", () => {
    expect(classifyRole("src/a.spec.tsx")).toBe("test");
    expect(classifyRole("src/__tests__/a.ts")).toBe("test");
    expect(classifyRole("e2e/flow.ts")).toBe("test");
    expect(classifyRole("src/testing.ts")).toBe("source");
    expect(classifyRole("types/api.test-d.ts")).toBe("test");
    expect(classifyRole("packages/app/test/helpers.ts")).toBe("test");
    expect(classifyRole("src/testing/utils.ts")).toBe("source");
    expect(classifyRole("src/test-utils.ts")).toBe("source");
  });
});

describe("exclusion", () => {
  const manifests = (...names: Array<string>) =>
    names.map((name) => ({ file: "package.json", manifest: { name } as PackageJsonManifest }));
  const options = { excludeRepos: ["Some/Repo"], excludeEffectPackageDefiners: true };

  it("excludes the Effect-TS org, configured repos and Effect copies", () => {
    expect(exclusionReason("Effect-TS/effect", [], options)).toBe("effect-ts-org");
    expect(exclusionReason("effect-ts/website", [], options)).toBe("effect-ts-org");
    expect(exclusionReason("some/repo", [], options)).toBe("configured");
    expect(exclusionReason("x/fork", manifests("@effect/platform"), options)).toBe(
      "defines-effect-package",
    );
    expect(exclusionReason("x/app", manifests("my-app", "@my/effect"), options)).toBeUndefined();
    expect(
      exclusionReason("x/fork", manifests("effect"), {
        ...options,
        excludeEffectPackageDefiners: false,
      }),
    ).toBeUndefined();
  });
});
