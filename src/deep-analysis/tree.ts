import type { FileRole, SourceExtension } from "../domain/usage.ts";

/**
 * The file inventory of a clone, read from its git tree listing instead of
 * the filesystem: a blobless clone knows every path before a single file is
 * checked out, so selection and deep analysis agree on what counts as a
 * source file (and where it sits in the repository's conventions) without
 * downloading anything.
 */

/** One `git ls-tree -r -z` entry. */
export interface TreeEntry {
  readonly mode: string;
  readonly type: string;
  /** Path relative to the repository root, `/`-separated. */
  readonly path: string;
}

/**
 * Parses `git ls-tree -r -z --full-tree HEAD` output: NUL-terminated
 * `<mode> SP <type> SP <object> TAB <path>` records, paths unquoted.
 */
export const parseLsTree = (output: string): ReadonlyArray<TreeEntry> => {
  const entries: Array<TreeEntry> = [];
  for (const record of output.split("\0")) {
    const tab = record.indexOf("\t");
    if (tab < 0) continue;
    const [mode, type] = record.slice(0, tab).split(" ");
    if (mode === undefined || type === undefined) continue;
    entries.push({ mode, type, path: record.slice(tab + 1) });
  }
  return entries;
};

/** Regular files only: no symlinks (`120000`), no submodules (`commit`). */
const isRegularFile = (entry: TreeEntry): boolean =>
  entry.type === "blob" && (entry.mode === "100644" || entry.mode === "100755");

/**
 * Directories that never contain repository-authored source: dependencies,
 * VCS metadata, and the usual generated build output and vendored code.
 * Excluding build output keeps the inventory from counting compiled copies
 * of the same files. Hidden directories (any `.name` segment) are excluded
 * too: besides tool configuration they are where repositories keep
 * reference clones (`.repos/effect/`), which would otherwise make a copy of
 * Effect look like the repository's own code — or like an Effect copy.
 */
export const excludedDirectories: ReadonlyArray<string> = [
  "node_modules",
  ".git",
  "dist",
  "build",
  "out",
  "coverage",
  "vendor",
];

const excludedDirectorySet = new Set(excludedDirectories);

/** Whether a path lies below an excluded (or hidden) directory. */
export const isExcludedPath = (path: string): boolean => {
  const segments = path.split("/");
  for (let i = 0; i < segments.length - 1; i++) {
    const segment = segments[i] ?? "";
    if (excludedDirectorySet.has(segment) || (segment.startsWith(".") && segment.length > 1)) {
      return true;
    }
  }
  return false;
};

const testFileNames = /\.(test|spec)\.(ts|tsx|mts|cts)$/;
const testDeclarationNames = /\.test-d\.(ts|mts|cts)$/;
const testDirectories = /(^|\/)(__tests__|tests?|spec|e2e|cypress|playwright)(\/|$)/;

const generatedFileNames = /(\.gen|\.generated|[._]pb|_grpc_pb)\.(ts|tsx|mts|cts)$/;
const generatedDirectories =
  /(^|\/)(__generated__|_generated|\.generated|generated|autogen|auto-generated)(\/|$)/;

/**
 * The role of a source file from its path alone. Heuristic, applied
 * uniformly so every row can be split by role:
 *
 * - `generated` (checked first: generated tests are still generated):
 *   `*.gen.ts`, `*.generated.ts`, protobuf `*_pb.ts` / `*.pb.ts`, or a
 *   `__generated__/`, `_generated/`, `generated/`, `autogen/` directory;
 * - `test`: `*.test.ts`, `*.spec.tsx`, `*.test-d.ts`, …, or a `__tests__/`,
 *   `test/`, `tests/`, `spec/`, `e2e/`, `cypress/`, `playwright/` directory;
 * - `source` otherwise.
 *
 * Plain `gen/` directories are deliberately not matched: they hold
 * generators as often as generated code. Their output is still caught when
 * the files are read, by `hasGeneratedHeader`. A `test/`-style directory
 * that holds non-test helpers still counts as test code, which is the useful
 * side of the error for adoption analysis.
 */
export const classifyRole = (file: string): FileRole =>
  generatedFileNames.test(file) || generatedDirectories.test(file)
    ? "generated"
    : testFileNames.test(file) || testDeclarationNames.test(file) || testDirectories.test(file)
      ? "test"
      : "source";

/**
 * The markers code generators put at the top of their output, each phrased
 * so it describes the file itself: `@generated` (Relay, GraphQL Codegen,
 * protobuf-es…), "This file is (auto-)generated", "auto-generated file / by
 * / from …", "Code generated by …", and a comment line that starts with
 * "Generated by / from / …" ("// Generated by X. Do not edit.") — not a
 * wrapped prose line that merely begins with the word.
 */
const generatedMarkers = [
  /@generated\b/,
  /\b(this|the) (file|code|module) (is|was|has been) (auto(matically)?[- ]?)?generated\b/i,
  /\b(auto-?|automatically )generated(?=\s*(file|code|by|from|with|using)\b|\s*[-.:!,;)]|\s*\*\/|\s*$)/im,
  /\bcode generated by\b/i,
  /^\s*(\/\/+|\/\*+|\*)?\s*(auto-?)?generated\s+(by|from|with|using|file|code)\b/im,
];

/**
 * "DO NOT EDIT" alone is ambiguous — hand-copied code says it too ("DO NOT
 * MODIFY THIS FILE. Adapted from …") — so it only counts next to some
 * mention of generation in the same header.
 */
const doNotEdit = /\bdo not (edit|modify)\b/i;
const generationWord = /\bgenerat(ed|or|ion)\b|\bcodegen\b/i;

/** How far into a file the leading comment block is looked for. */
const headerLength = 2048;

const directive = /^\s*["'][a-z ]+["'];?\s*$/;

/**
 * The text of a file's leading comment block: the comments before the first
 * line of code (a shebang, directives such as `"use client"` and blank lines
 * may precede or interleave). Comments further down — a component's JSDoc,
 * a comment inside a template literal — say nothing about the file.
 */
export const leadingComments = (text: string): string => {
  const comments: Array<string> = [];
  let inBlock = false;
  for (const line of text.slice(0, headerLength).split("\n")) {
    const trimmed = line.trim();
    if (inBlock) {
      comments.push(trimmed);
      if (trimmed.includes("*/")) inBlock = false;
    } else if (trimmed === "" || trimmed.startsWith("#!") || directive.test(trimmed)) {
      continue;
    } else if (trimmed.startsWith("//")) {
      comments.push(trimmed);
    } else if (trimmed.startsWith("/*")) {
      comments.push(trimmed);
      inBlock = !trimmed.includes("*/", 2);
    } else {
      break;
    }
  }
  return comments.join("\n");
};

/** Whether a file's leading comment block says a tool wrote it. */
export const hasGeneratedHeader = (text: string): boolean => {
  const header = leadingComments(text);
  if (header === "") return false;
  return (
    generatedMarkers.some((marker) => marker.test(header)) ||
    (doNotEdit.test(header) && generationWord.test(header))
  );
};

const sourceNames = /\.(ts|tsx|mts|cts)$/;
const declarationNames = /\.d\.(ts|mts|cts)$/;

/**
 * Every `package.json` outside the excluded directories, sorted: the
 * manifests the selection probes read and the workspace packages files are
 * assigned to. Same exclusions as the source inventory, so a vendored copy
 * can neither make a repository an adopter nor get it excluded.
 */
export const manifestPaths = (entries: ReadonlyArray<TreeEntry>): ReadonlyArray<string> =>
  entries
    .filter(
      (entry) =>
        isRegularFile(entry) &&
        (entry.path === "package.json" || entry.path.endsWith("/package.json")) &&
        !isExcludedPath(entry.path),
    )
    .map((entry) => entry.path)
    .sort();

/** Whether the tree has a regular file at the given root-relative path. */
export const hasFile = (entries: ReadonlyArray<TreeEntry>, path: string): boolean =>
  entries.some((entry) => entry.path === path && isRegularFile(entry));

/** The directory of a manifest path: `""` for the root, `packages/a` for `packages/a/package.json`. */
export const directoryOf = (path: string): string => {
  const slash = path.lastIndexOf("/");
  return slash < 0 ? "" : path.slice(0, slash);
};

/**
 * The workspace package a file belongs to: the longest directory prefix of
 * the file that holds a `package.json`, `""` (the repository root) when none
 * does.
 */
export const packageDirOf = (file: string, packageDirs: ReadonlySet<string>): string => {
  let dir = directoryOf(file);
  while (dir !== "") {
    if (packageDirs.has(dir)) return dir;
    dir = directoryOf(dir);
  }
  return "";
};

export interface SourceFileEntry {
  readonly file: string;
  readonly extension: SourceExtension;
  readonly role: FileRole;
  /** `*.d.ts` / `*.d.mts` / `*.d.cts`: counted, never parsed as usage. */
  readonly declaration: boolean;
  /** The workspace package directory the file belongs to (see `packageDirOf`). */
  readonly packageDir: string;
}

const extensionOf = (file: string): SourceExtension =>
  file.endsWith(".tsx")
    ? "tsx"
    : file.endsWith(".mts")
      ? "mts"
      : file.endsWith(".cts")
        ? "cts"
        : "ts";

/**
 * Every TypeScript file of the tree (declarations included, build output and
 * dependencies excluded), sorted by path, with its role and workspace
 * package.
 */
export const sourceFiles = (
  entries: ReadonlyArray<TreeEntry>,
  packageDirs: ReadonlySet<string>,
): ReadonlyArray<SourceFileEntry> =>
  entries
    .filter(
      (entry) =>
        isRegularFile(entry) && sourceNames.test(entry.path) && !isExcludedPath(entry.path),
    )
    .map((entry) => entry.path)
    .sort()
    .map((file): SourceFileEntry => ({
      file,
      extension: extensionOf(file),
      role: classifyRole(file),
      declaration: declarationNames.test(file),
      packageDir: packageDirOf(file, packageDirs),
    }));

/** Sparse-checkout negations mirroring `isExcludedPath` (gitignore syntax). */
const excludedPatterns: ReadonlyArray<string> = [
  ...excludedDirectories.filter((dir) => dir !== ".git").map((dir) => `!${dir}/`),
  "!.*/",
];

/**
 * Sparse-checkout patterns (non-cone, gitignore syntax) of the selection
 * checkout: the manifests and the pnpm workspace file, nothing else.
 */
export const selectionPatterns: ReadonlyArray<string> = [
  "**/package.json",
  "/pnpm-workspace.yaml",
  ...excludedPatterns,
];

/**
 * Sparse-checkout patterns of the analysis checkout: the selection files plus
 * every non-declaration TypeScript file outside the excluded directories —
 * the same set `sourceFiles` inventories, so no other blob is downloaded.
 */
export const analysisPatterns: ReadonlyArray<string> = [
  "**/package.json",
  "/pnpm-workspace.yaml",
  "*.ts",
  "*.tsx",
  "*.mts",
  "*.cts",
  "!*.d.ts",
  "!*.d.mts",
  "!*.d.cts",
  ...excludedPatterns,
];
